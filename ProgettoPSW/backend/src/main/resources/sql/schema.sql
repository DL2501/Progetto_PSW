

CREATE TABLE Utente (
    UID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Nome_Utente  VARCHAR(255) NOT NULL,
    Nome         VARCHAR(50),
    Cognome      VARCHAR(50),
    Email        VARCHAR(90) NOT NULL,
    Data_Nascita DATE NOT NULL,
    CONSTRAINT pk_utente PRIMARY KEY (UID)
);


CREATE TABLE Watchable (
    Watchable_ID                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    Tipo_Contenuto              VARCHAR(31)                              NOT NULL,
    IMDB_ID                     VARCHAR(50)                              NOT NULL,
    Titolo                      VARCHAR(255)                             NOT NULL,
    Genere                      VARCHAR(50)                              NOT NULL,
    Sinossi                     VARCHAR(2000),
    Copertina                   VARCHAR(500),
    Data_Uscita                 DATE                                     NOT NULL,
    Valutazione_Media           DOUBLE PRECISION,
    Version                     BIGINT                                   NOT NULL,

    -- Colonne condivise (Film / Episodio / SerieTV)
    Durata                      INTEGER,
    Regista                     VARCHAR(100),
    Numero_Voti                 INTEGER,
    Stato                       VARCHAR(50),

    -- Colonne specifiche per Film
    Data_Apertura_Prenotazioni  DATE,
    Data_Anteprima              DATE,
    Capacità_Massima            INTEGER,
    Posti_Anteprima_Disponibili INTEGER,

    -- Colonne specifiche per SerieTV
    Stagioni                    INTEGER,
    Numero_Episodi              INTEGER,
    Ideatore                    VARCHAR(100),
    Data_Fine                   DATE,

    -- Colonne specifiche per Episodio
    Stagione                    INTEGER,
    Numero                      INTEGER,
    SerieTV                     INTEGER,

    CONSTRAINT pk_watchable PRIMARY KEY (Watchable_ID),
    CONSTRAINT uc_watchable_imdb_id UNIQUE (IMDB_ID),
    CONSTRAINT fk_episodio_serietv FOREIGN KEY (SerieTV) REFERENCES Watchable (Watchable_ID)
);

-- 3. Tabella Prenotazione
CREATE TABLE Prenotazione (
                              Prenotazione_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                              Codice_Biglietto  VARCHAR(40)                              NOT NULL,
                              Data_Prenotazione TIMESTAMP                                NOT NULL,
                              Prezzo_Pagato     DOUBLE PRECISION                         NOT NULL,
                              Validità          BOOLEAN                                  NOT NULL,
                              Utente_ID         INTEGER                                  NOT NULL,
                              Film_ID           INTEGER                                  NOT NULL,
                              CONSTRAINT pk_prenotazione PRIMARY KEY (Prenotazione_ID),
                              CONSTRAINT uc_prenotazione_codice_biglietto UNIQUE (Codice_Biglietto),
                              CONSTRAINT fk_prenotazione_utente FOREIGN KEY (Utente_ID) REFERENCES Utente (UID),
                              CONSTRAINT fk_prenotazione_film FOREIGN KEY (Film_ID) REFERENCES Watchable (Watchable_ID)
);

-- 4. Tabella Visione_Watchable
CREATE TABLE Visione_Watchable (
                                   VWID          INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                                   Stato_Visione VARCHAR(50),
                                   Valutazione   INTEGER,
                                   In_Videoteca  BOOLEAN                                  NOT NULL,
                                   Utente_ID     INTEGER                                  NOT NULL,
                                   Watchable_ID  INTEGER                                  NOT NULL,
                                   CONSTRAINT pk_visione_watchable PRIMARY KEY (VWID),
                                   CONSTRAINT Visione_Watchable_UC UNIQUE (Utente_ID, Watchable_ID),
                                   CONSTRAINT fk_vw_utente FOREIGN KEY (Utente_ID) REFERENCES Utente (UID),
                                   CONSTRAINT fk_vw_watchable FOREIGN KEY (Watchable_ID) REFERENCES Watchable (Watchable_ID)
);